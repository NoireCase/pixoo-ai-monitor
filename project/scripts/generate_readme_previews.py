"""Reproducible README diagrams from real renderer + explicit synthetic data.

No network, keyring, app import, configuration loading or Bluetooth access.
Annotations are outside the native 16x16 screen.
"""
from datetime import datetime,timedelta,timezone
from decimal import Decimal
from pathlib import Path
import sys
from PIL import Image,ImageDraw,ImageFont

ROOT=Path(__file__).resolve().parents[1]
sys.path.insert(0,str(ROOT))
from providers.base import Reading
from display.renderer import render_configured

NOW=datetime(2026,10,29,10,tzinfo=timezone(timedelta(hours=8)))
CFG={'display_style':'b3','refresh_seconds':120,'display_data_stale_seconds':360}

def sample(pid='go',window='5H',value=76,*,now=NOW,seconds=12300,status='OK'):
    return Reading(pid,pid,source='README DEMO',window=window,
                   remaining_percent=None if pid=='ds' else value,
                   remaining_value=Decimal(str(value)) if pid=='ds' else None,
                   unit='CNY' if pid=='ds' else '%',status=status,
                   last_updated=now.isoformat(),
                   reset_at=None if seconds is None else (now+timedelta(seconds=seconds)).isoformat())

def groups():
    pages=[]
    for pid,window,value,label in [('go','5H',76,'O / H - 76%'),('go','7D',47,'O / W - 47%'),
                                  ('go','30D',12,'O / M - 12%'),('cx','5H',99,'G / H - 99%'),
                                  ('cx','7D',100,'G / W - 100'),('ds','',18.35,'D / YEN - balance')]:
        pages.append((f'{pid}_{window or "cny"}'.lower(),label,sample(pid,window,value),NOW))
    quota=[(f'quota_{p}',f'{p}% remaining',sample(window='7D',value=p),NOW) for p in (100,60,59,20,19,0)]
    timers=[]
    for name,seconds,label in [('3h25',12300,'3h25: G G G R gray'),('3h35',12900,'3h35: G G G G gray'),
                               ('4h',14400,'4h: G G G G gray'),('1h20',4800,'1h20: G R gray gray gray'),
                               ('20m',1200,'20m: R gray gray gray gray'),('0m',0,'0m: all gray'),
                               ('5h',18000,'5h: all green'),('30m',1800,'30m: first cell red'),
                               ('missing',None,'No reset time: all gray')]:
        timers.append(('reset_'+name,label,sample(seconds=seconds),NOW))
    errors=[(state.lower(),state,sample(status=state),NOW) for state in ('NOT_CONFIGURED','ERROR','STALE')]
    price=[]
    for name,t in [('peak',NOW),('off_peak',NOW.replace(hour=12)),('unknown',NOW.replace(year=2027))]:
        price.append(('ds_'+name,name.upper(),sample('ds','',18.35,now=t),t))
    return {'pages':pages,'quota-states':quota,'countdown-states':timers,'error-states':errors,'deepseek-states':price}

def make_previews(out=None):
    out=Path(out) if out is not None else ROOT/'docs'/'screens'
    out.mkdir(parents=True,exist_ok=True)
    try: font=ImageFont.truetype('arial.ttf',18)
    except OSError: font=ImageFont.load_default()
    files=[]
    for group,cases in groups().items():
        board=Image.new('RGB',(1080,75+((len(cases)+2)//3)*390),(22,25,32));draw=ImageDraw.Draw(board)
        draw.text((20,15),'DEMO DATA | Native 16x16 renderer output | Not a device photograph',font=font,fill='white')
        draw.text((20,40),'Nearest-neighbor enlargement; no real account data or credentials.',font=font,fill=(180,190,205))
        for i,(name,label,r,t) in enumerate(cases):
            image=render_configured(r,CFG,t)
            assert image.size==(16,16) and image.mode=='RGB'
            original=out/(name+'_16.png');enlarged=out/(name+'_320.png')
            image.save(original);large=image.resize((320,320),Image.Resampling.NEAREST);large.save(enlarged)
            files.extend([original,enlarged])
            x=20+(i%3)*360;y=85+(i//3)*390
            draw.text((x,y),'DEMO '+label,font=font,fill='white');board.paste(large,(x,y+35))
        path=out/(group+'.png');board.save(path);files.append(path)
    (out/'README.txt').write_text('All screens are explicit synthetic examples generated by scripts/generate_readme_previews.py.\nThe native 16x16 pixel content uses the production B3 renderer; captions sit outside the screen.\nNo API, credentials, device metadata or live account balances are accessed.\n',encoding='utf-8')
    return files

if __name__=='__main__':
    print('Generated',len(make_previews()),'PNG documentation files from synthetic demo data.')
